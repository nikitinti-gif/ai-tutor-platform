def build_diagnostic_critical_review_prompt(
    *,
    topic: str,
    tasks: list[dict],
    student_solution: str,
    first_result: str,
) -> str:
    level_codes = ("easy", "medium", "hard")
    task_lines = "\n".join(
        f"{index}. level={level_codes[index - 1]} ({task['level']})\n"
        f"Задание: {task['task']}\nЭталон: {task['teacher_answer']}"
        for index, task in enumerate(tasks, start=1)
    )
    return f"""
Ты — независимый критик первой диагностической проверки по информатике.
Не доверяй первому заключению и не повторяй его формулировки автоматически.

Самостоятельно реши каждое из трёх заданий. Для каждого уровня отдельно:
- сравни решение ученика с условием и проверенным эталоном;
- проверь вычисления, логику, все ограничения и граничные значения;
- попытайся опровергнуть первое заключение;
- если вывод подтверждается, укажи конкретное доказательство;
- если вывод ошибочен, верни исправленный статус и точную причину.

Значение confidence показывает уверенность именно независимой перепроверки.
Объявлять тему освоенной можно только при трёх доказанно верных уровнях.
Верни только JSON диагностической схемы.

ТЕМА: {topic}

ЗАДАНИЯ И ЭТАЛОНЫ:
{task_lines}

ОТВЕТ УЧЕНИКА:
{student_solution}

ПЕРВОЕ ЗАКЛЮЧЕНИЕ:
{first_result}
""".strip()


