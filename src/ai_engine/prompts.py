def build_diagnostic_probe_rephrase_prompt(
    *,
    skill_id: str,
    skill_name: str,
    canonical_prompt: str,
    answer_format: str,
    previous_prompts: list[str] | None = None,
) -> str:
    """Ask AI for variety without giving it control over correctness."""
    previous = "\n".join(f"- {item}" for item in (previous_prompts or []))
    return f"""
Ты формулируешь короткую диагностическую мини-пробу по информатике.
Проверяй только навык {skill_id} ({skill_name}).

Переформулируй канонический вопрос живым и понятным русским языком, но:
- не меняй числа, данные, логические условия и требуемое действие;
- не добавляй подсказку или правильный ответ;
- не смешивай несколько навыков;
- сохрани формат ответа: {answer_format};
- вопрос должен быть самодостаточным и не длиннее 500 символов.

КАНОНИЧЕСКИЙ ВОПРОС:
{canonical_prompt}

РАНЕЕ ПОКАЗАННЫЕ ФОРМУЛИРОВКИ (не повторяй дословно):
{previous or "нет"}

Верни только JSON с полем prompt.
""".strip()


def build_live_diagnostic_probe_prompt(*, task_number: int, operation_index: int, skill_id: str, fields: dict[str, object], previous_prompts: list[str] | None = None) -> str:
    """Request genuinely new wording for fresh Python-owned inputs."""
    previous = "\n".join(f"- {item}" for item in (previous_prompts or []))
    placeholders_by_operation = {
        (5, 0): ("conversion_task",), (5, 1): ("n",),
        (5, 2): ("binary", "suffix"),
        (5, 3): ("start", "limit", "expression", "boundary"),
        (14, 0): ("n", "base"), (14, 1): ("digit", "value"),
        (14, 2): ("count",), (27, 0): ("points",),
        (27, 1): ("sums",), (27, 2): ("labels", "target"),
        (27, 3): ("distances",),
    }
    intents = {
        (5, 0): "перевести десятичное число в двоичную запись",
        (5, 1): "определить ветку 1 для нечётного N и ветку 0 для чётного N по последнему двоичному биту",
        (5, 2): "дописать заданный суффикс справа к готовой двоичной записи",
        (5, 3): "найти наибольшее целое N в указанном диапазоне, удовлетворяющее строгому неравенству 3N+2 < boundary",
        (14, 0): "найти остаток первого деления при переводе числа в систему с данным основанием",
        (14, 1): "определить чётность числового значения цифры; ответ только да или нет",
        (14, 2): "учесть полученные остатки и последнее ненулевое частное при подсчёте числа разрядов",
        (27, 0): "определить число естественных кластеров в наборе точек points",
        (27, 1): "выбрать медоид A, B или C по минимальной сумме расстояний",
        (27, 2): "посчитать метки target в последовательности labels",
        (27, 3): "найти максимальное из расстояний distances от медоида",
    }
    placeholders = ", ".join("{" + name + "}" for name in placeholders_by_operation[(task_number, operation_index)])
    preview = ", ".join(f"{name}={value}" for name, value in fields.items())
    return f"""
Создай новую короткую диагностическую мини-пробу по навыку {skill_id}.
Проверяемое действие: {intents[(task_number, operation_index)]}.

Верни prompt_template — самостоятельный вопрос ученику на естественном русском языке.
Python уже создал и проверил данные: {preview}.

Жёсткие правила prompt_template:
- сам придумай композицию и формулировку, не копируй предыдущие вопросы;
- используй каждый плейсхолдер ровно один раз: {placeholders};
- не используй другие плейсхолдеры и не пиши цифры вне плейсхолдеров;
- не сообщай и не подсказывай ответ;
- проверяй только указанное действие, без второго вычислительного шага;
- задай явный вопрос со знаком вопроса; длина до 500 символов;
- значения уже проверены и будут подставлены Python после проверки текста.
{('- плейсхолдер {conversion_task} содержит всё проверяемое действие; сохрани его целиком и добавляй только нейтральное обрамление.' if (task_number, operation_index) == (5, 0) else '')}

Ранее показанные формулировки (создай заметно другую):
{previous or 'нет'}

Верни только JSON:
{{"prompt_template": "..."}}.
""".strip()
